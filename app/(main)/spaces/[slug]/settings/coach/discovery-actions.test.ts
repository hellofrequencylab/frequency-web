import { beforeEach, describe, expect, it, vi } from 'vitest'
const m = vi.hoisted(() => ({ actor: vi.fn(), space: vi.fn(), caps: vi.fn(), load: vi.fn(), write: vi.fn(), evidence: vi.fn(), context: vi.fn() }))
vi.mock('@/lib/auth', () => ({ getMyProfileId: m.actor }))
vi.mock('@/lib/spaces/store', () => ({ getSpaceById: m.space }))
vi.mock('@/lib/spaces/discovery-access', () => ({ resolveDiscoveryEditor: async (id: string) => { const actor = await m.actor(); const space = await m.space(id); return actor && space && (await m.caps(space)).canEditProfile ? { actor, space } : null } }))
vi.mock('@/lib/spaces/private-state', () => ({ loadSpaceDiscoveryConsent: m.load, writeSpaceDiscoveryConsent: m.write, loadSpaceCoachProfile: m.context }))
vi.mock('@/lib/spaces/analytics', () => ({ getSpaceProfileEvidence: m.evidence }))
vi.mock('@/lib/sites/host', () => ({ appOrigin: () => 'https://frequencylocal.com' }))
vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }))
import { setSpaceDiscoveryConsent, reviewSpaceDiscovery } from './discovery-actions'
import { grantDiscoveryConsent } from '@/lib/spaces/discovery-consent'
const now = new Date()
const grant = grantDiscoveryConsent('editor-a', 'grant-a', new Date(now.getTime() - 60_000))
beforeEach(() => {
  vi.resetAllMocks()
  m.actor.mockResolvedValue('editor-a')
  m.space.mockImplementation(async (id) => ({ id, slug: `slug-${id}` }))
  m.caps.mockImplementation(async (space) => ({ canEditProfile: space.id === 'space-a' }))
  m.load.mockResolvedValue({ available: true, consent: grant })
  m.write.mockResolvedValue(true)
  m.context.mockResolvedValue({ available: true, profile: { audience: 'Neighbours', voice: 'Plain words' } })
  m.evidence.mockResolvedValue({ observedFrom: new Date(now.getTime() - 30 * 86400000).toISOString(), observedThrough: now.toISOString(), windowDays: 30, profileViews: 12, ctaClicks: 2 })
})
describe('discovery action boundaries', () => {
  it('denies another tenant before any private read or aggregate read', async () => {
    expect(await reviewSpaceDiscovery('space-b')).toEqual({ status: 'unavailable', reason: 'permission_denied' })
    expect(await setSpaceDiscoveryConsent('space-b', true)).toHaveProperty('error')
    expect(m.load).not.toHaveBeenCalled(); expect(m.evidence).not.toHaveBeenCalled(); expect(m.write).not.toHaveBeenCalled()
  })
  it('requires explicit current purpose consent before reading aggregates', async () => {
    m.load.mockResolvedValue({ available: true, consent: { ...grant, revokedAt: now.toISOString() } })
    expect(await reviewSpaceDiscovery('space-a')).toEqual({ status: 'unavailable', reason: 'consent_required' })
    expect(m.evidence).not.toHaveBeenCalled()
  })
  it('blocks expired permission before reading aggregates', async () => {
    m.load.mockResolvedValue({ available: true, consent: { ...grant, expiresAt: new Date(now.getTime() - 1).toISOString() } })
    expect(await reviewSpaceDiscovery('space-a')).toEqual({ status: 'unavailable', reason: 'consent_required' })
    expect(m.evidence).not.toHaveBeenCalled()
  })
  it('discards in-flight observations after revocation or permission loss', async () => {
    m.evidence.mockImplementationOnce(async () => { m.load.mockResolvedValue({ available: true, consent: { ...grant, revokedAt: new Date().toISOString() } }); return { windowDays: 30, observedFrom: new Date(now.getTime()-86400000).toISOString(), observedThrough: now.toISOString(), profileViews: 12, ctaClicks: 2 } })
    expect(await reviewSpaceDiscovery('space-a')).toEqual({ status: 'unavailable', reason: 'consent_required' })
    m.load.mockResolvedValue({ available: true, consent: grant })
    m.evidence.mockImplementationOnce(async () => { m.caps.mockResolvedValue({ canEditProfile: false }); return {} })
    expect(await reviewSpaceDiscovery('space-a')).toEqual({ status: 'unavailable', reason: 'permission_denied' })
  })
  it('uses only this Space profile aggregate scope and preserves honest counting units', async () => {
    const result = await reviewSpaceDiscovery('space-a')
    expect(result.status).toBe('completed')
    if (result.status !== 'completed') throw Error('Expected actual observation result')
    expect(m.evidence).toHaveBeenCalledWith('space-a', 30)
    expect(result.coaching.recommendations.every(task => task.evidence.scope.spaceId === 'space-a' && task.provenance === 'first-party reader' && task.basis === 'limited measurement')).toBe(true)
    expect(result.observationLimits.join(' ')).toContain('not unique visitors')
  })
  it('mints a fresh grant and saves revocation without touching writing preferences', async () => {
    const saved = await setSpaceDiscoveryConsent('space-a', true)
    expect(saved).toHaveProperty('data.purpose', 'discovery_coaching')
    expect(m.write).toHaveBeenCalledWith('space-a', expect.objectContaining({ grantedBy: 'editor-a', purpose: 'discovery_coaching', revokedAt: null }))
    expect(m.write.mock.calls[0][1].id).not.toBe(grant.id)
    await setSpaceDiscoveryConsent('space-a', false)
    expect(m.write.mock.calls[1][1]).toMatchObject({ id: grant.id, revokedAt: expect.any(String) })
    expect(m.write.mock.calls[1][1]).not.toHaveProperty('coach_profile')
  })
  it('fails closed when storage is unavailable and does not fabricate zero data', async () => {
    m.load.mockResolvedValue({ available: false, consent: null })
    expect(await setSpaceDiscoveryConsent('space-a', true)).toHaveProperty('error')
    expect(m.write).not.toHaveBeenCalled()
    expect(await reviewSpaceDiscovery('space-a')).toEqual({ status: 'unavailable', reason: 'consent_required' })
    expect(m.evidence).not.toHaveBeenCalled()
  })
})
