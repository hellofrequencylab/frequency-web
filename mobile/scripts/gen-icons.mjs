// Generates src/theme/icons.generated.ts from the Frequency icon sprite
// (design_handoff/frequency/assets/icons/frequency-icons.svg): one standalone <svg> string per
// symbol, drawn on the 24px grid with the 1.75 stroke, in `currentColor` so <Icon color> sets it.
// Run `pnpm gen:icons` after the design export changes. Never edit the output by hand.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const sprite = readFileSync(path.resolve(here, '../../design_handoff/frequency/assets/icons/frequency-icons.svg'), 'utf8')
const out = path.resolve(here, '../src/theme/icons.generated.ts')

const icons = {}
for (const m of sprite.matchAll(/<symbol([^>]*)>([\s\S]*?)<\/symbol>/g)) {
  const attrs = m[1]
  const id = /id="([^"]+)"/.exec(attrs)?.[1]
  if (!id) continue
  const svgAttrs = attrs.replace(/\s*id="[^"]+"/, '')
  icons[id] = `<svg xmlns="http://www.w3.org/2000/svg"${svgAttrs}>${m[2].trim()}</svg>`
}

const names = Object.keys(icons)
const body = [
  '// GENERATED by scripts/gen-icons.mjs from design_handoff/frequency/assets/icons/frequency-icons.svg.',
  '// Do not edit. Run `pnpm gen:icons`.',
  '',
  `export const ICONS = ${JSON.stringify(icons, null, 2)} as const`,
  '',
  'export type IconName = keyof typeof ICONS',
  '',
].join('\n')
writeFileSync(out, body)
console.log(`wrote ${names.length} icons to ${path.relative(process.cwd(), out)}`)
