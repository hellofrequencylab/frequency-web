// STYLES PER DESIGN (ADR-1737): the stylesheet half of what lib/theme/design-fonts/active.ts does for faces.
//
// A design other than DAWN ships its own sheets: app/themes/<id>.css (the alias layer) and
// app/themes/<id>/*.css (the generated core, the product kits, the page sheets). A CSS import is NOT
// tree-shaken by a runtime `SITE_DESIGN === …` branch, so a component that imported one of those sheets
// directly put it into EVERY deploy's graph, DAWN's included. Nothing imports them directly any more.
// Each sheet has one STUB in app/themes/active/<name>.ts, and code imports the stub:
//
//   import '@/app/themes/active/kit-site'
//
// scripts/write-design-assets.mjs (prebuild, predev, and `pnpm design:use`) rewrites every stub from
// NEXT_PUBLIC_SITE_DESIGN: under that design the stub is one `import '../<id>/<name>.css'`, under any
// other it imports nothing. One stub per sheet keeps a Frequency build's per-route loading exactly as it
// was (a sheet still loads only where its importer renders) and keeps the import ORDER (core before the
// alias layer, lib/theme/design.test.ts). The committed stubs are DAWN's: empty.
//
// This module is pure (no disk writes), so lib/theme/design.test.ts can render both switches.
import { existsSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

export const STUB_DIR = 'app/themes/active'
/** The stub name of a design's alias layer (app/themes/<id>.css). Every other stub is its sheet's basename. */
export const ALIAS_STUB = 'alias'
export const STUB_HEADER =
  "// GENERATED by scripts/write-design-assets.mjs from NEXT_PUBLIC_SITE_DESIGN (scripts/lib/design-styles.mjs).\n// The committed copy is DAWN's, which loads nothing; do not commit another design's (lib/theme/design.test.ts).\n"

/**
 * Every sheet of every non-DAWN design, as { stub, design, href } (href relative to STUB_DIR).
 * @param {readonly string[]} designIds
 * @param {string} [root]
 * @returns {{ stub: string, design: string, href: string }[]}
 */
export function designSheets(designIds, root = '.') {
  /** @type {{ stub: string, design: string, href: string }[]} */
  const sheets = []
  for (const id of designIds) {
    if (id === 'dawn') continue
    if (existsSync(join(root, `app/themes/${id}.css`))) sheets.push({ stub: ALIAS_STUB, design: id, href: `../${id}.css` })
    const dir = join(root, `app/themes/${id}`)
    if (!existsSync(dir)) continue
    for (const f of readdirSync(dir).sort()) {
      if (f.endsWith('.css')) sheets.push({ stub: f.slice(0, -4), design: id, href: `../${id}/${f}` })
    }
  }
  return sheets
}

/**
 * The content of every stub for the design this build wears: { [stubName]: source }. A stub whose sheet
 * belongs to another design (or that DAWN never has) is the empty module.
 */
/**
 * @param {string} active
 * @param {readonly string[]} designIds
 * @param {string} [root]
 * @returns {Record<string, string>}
 */
export function renderStubs(active, designIds, root = '.') {
  /** @type {Record<string, string>} */
  const out = {}
  for (const s of designSheets(designIds, root)) {
    const prev = out[s.stub]
    if (prev && /^import /m.test(prev) && s.design !== active) continue
    out[s.stub] =
      s.design === active
        ? `${STUB_HEADER}// The ${active} design's ${s.stub === ALIAS_STUB ? 'alias layer' : `\`${s.stub}\` sheet`}.\nimport '${s.href}'\n\nexport {}\n`
        : `${STUB_HEADER}// The ${s.design} design's ${s.stub === ALIAS_STUB ? 'alias layer' : `\`${s.stub}\` sheet`}. This build wears ${active}, so it loads nothing.\nexport {}\n`
  }
  return out
}
