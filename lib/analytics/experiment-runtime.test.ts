import { beforeEach, describe, expect, it, vi } from 'vitest'
vi.mock('next/headers', () => ({ cookies: async () => ({ get: () => undefined }) }))
const mock = vi.hoisted(() => ({ caller: vi.fn(), profileId: vi.fn(), realRole: vi.fn(), consent: vi.fn(), rpc: vi.fn(), team: vi.fn() }))
vi.mock('@/lib/auth', () => ({ getCallerProfile: mock.caller, getMyProfileId: mock.profileId, getRealCallerWebRole: mock.realRole }))
vi.mock('@/lib/consent/consent', () => ({ hasConsent: mock.consent }))
vi.mock('@/lib/supabase/admin', () => ({ createAdminClient: () => ({ rpc: mock.rpc, from: () => ({ select: () => ({ eq: () => ({ maybeSingle: mock.team }) }) }) }) }))
import { memberExperiment, exposeMemberExperiment, recordExperimentOutcomes } from './experiment-runtime'
beforeEach(() => {
  vi.clearAllMocks()
  mock.caller.mockResolvedValue({ id: 'member', webRole: 'member' })
  mock.profileId.mockResolvedValue('member')
  mock.realRole.mockResolvedValue('member')
  mock.consent.mockResolvedValue(true)
  mock.team.mockResolvedValue({ data: null, error: null })
  mock.rpc.mockResolvedValue({ data: { id: 'experiment', variant: 'treatment' }, error: null })
})
describe('experiment member boundaries', () => {
  it('requires a signed-in consenting member and excludes real staff even in member preview', async () => {
    mock.realRole.mockResolvedValue('admin')
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
    expect(mock.rpc).not.toHaveBeenCalled()
    mock.realRole.mockResolvedValue('member'); mock.consent.mockResolvedValue(false)
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
    mock.caller.mockResolvedValue(null)
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
  })
  it('excludes team members in member preview and fails closed on a roster lookup error', async () => {
    mock.realRole.mockResolvedValue('none')
    mock.caller.mockResolvedValue({ id: 'member', webRole: 'none' })
    mock.team.mockResolvedValue({ data: { profile_id: 'member' }, error: null })
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
    mock.team.mockResolvedValue({ data: null, error: { message: 'offline' } })
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
    expect(mock.rpc).not.toHaveBeenCalled()
  })
  it('falls back to the unchanged surface when experiment storage is absent or the pilot is disabled', async () => {
    mock.rpc.mockResolvedValue({ data: null, error: { message: 'function does not exist' } })
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
    mock.rpc.mockResolvedValue({ data: null, error: null })
    expect(await memberExperiment('upcoming-next-step')).toBeNull()
  })
  it('does not turn assignment into exposure and binds exposure to the caller', async () => {
    expect(await memberExperiment('upcoming-next-step')).toEqual({ id: 'experiment', variant: 'treatment' })
    expect(mock.rpc).toHaveBeenCalledWith('analytics_experiment_assign', { _key: 'upcoming-next-step', _profile: 'member' })
    await exposeMemberExperiment('experiment')
    expect(mock.rpc).toHaveBeenCalledWith('analytics_experiment_expose', { _experiment: 'experiment', _profile: 'member' })
  })
  it('rejects arbitrary events, another actor and withdrawn consent without writing outcomes', async () => {
    await recordExperimentOutcomes('nav.page_view', 'member')
    await recordExperimentOutcomes('event.rsvp', 'other')
    mock.consent.mockResolvedValue(false)
    await recordExperimentOutcomes('event.rsvp', 'member')
    expect(mock.rpc).not.toHaveBeenCalled()
  })
  it('records only an authoritative RSVP and keeps a measurement outage from failing it', async () => {
    mock.rpc.mockRejectedValue(new Error('offline'))
    await expect(recordExperimentOutcomes('event.rsvp', 'member')).resolves.toBeUndefined()
  })
})
